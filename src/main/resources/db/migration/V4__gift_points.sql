-- V4: gift points (IBM step 10a)
-- The account holds the balance; the ledger records every change.
-- Safety rules enforced by the database:
--   * balance can never be negative
--   * at most one ledger entry of each type per order (no duplicate REDEEM / EARN / REFUND / REVERSE)

CREATE TABLE gift_point_accounts (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT  NOT NULL,
    balance INTEGER NOT NULL DEFAULT 0,
    version BIGINT  NOT NULL DEFAULT 0,                  -- optimistic lock against concurrent updates
    CONSTRAINT fk_gift_point_accounts_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_gift_point_accounts_user UNIQUE (user_id),
    CONSTRAINT ck_gift_point_accounts_balance CHECK (balance >= 0)
);

-- order_id references orders, which is created in V5; the foreign key is added there.
CREATE TABLE gift_point_transactions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT      NOT NULL,
    order_id   BIGINT,
    type       VARCHAR(10) NOT NULL,
    points     INTEGER     NOT NULL,                     -- signed change applied to the balance
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_gift_point_txn_account FOREIGN KEY (account_id) REFERENCES gift_point_accounts (id),
    CONSTRAINT uq_gift_point_txn_order_type UNIQUE (order_id, type),
    CONSTRAINT ck_gift_point_txn_type CHECK (type IN ('EARN', 'REDEEM', 'REFUND', 'REVERSE')),
    CONSTRAINT ck_gift_point_txn_sign CHECK (
        (type IN ('EARN', 'REFUND') AND points > 0) OR
        (type IN ('REDEEM', 'REVERSE') AND points < 0))
);

CREATE INDEX idx_gift_point_txn_account ON gift_point_transactions (account_id, created_at);
