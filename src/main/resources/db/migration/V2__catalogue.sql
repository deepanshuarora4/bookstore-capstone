-- V2: catalogue - categories, brands, products (IBM steps 3, 5, 6, 7, 7a)
-- "Related products" are derived from category/brand, so there is no relation table.

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    CONSTRAINT uq_categories_name UNIQUE (name)
);

CREATE TABLE brands (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    CONSTRAINT uq_brands_name UNIQUE (name)
);

CREATE TABLE products (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(200)   NOT NULL,
    author        VARCHAR(150)   NOT NULL,
    isbn          VARCHAR(13)    NOT NULL,
    description   VARCHAR(2000),
    price         NUMERIC(10, 2) NOT NULL,
    image_url     VARCHAR(500),
    stock_qty     INTEGER        NOT NULL,
    dispatch_days INTEGER        NOT NULL DEFAULT 0,
    active        BOOLEAN        NOT NULL DEFAULT TRUE,
    category_id   BIGINT         NOT NULL,
    brand_id      BIGINT         NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    version       BIGINT         NOT NULL DEFAULT 0,   -- optimistic lock for stock updates
    CONSTRAINT uq_products_isbn UNIQUE (isbn),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT fk_products_brand    FOREIGN KEY (brand_id)    REFERENCES brands (id),
    CONSTRAINT ck_products_price    CHECK (price >= 0.01),
    CONSTRAINT ck_products_stock    CHECK (stock_qty >= 0),            -- stock can never go negative
    CONSTRAINT ck_products_dispatch CHECK (dispatch_days BETWEEN 0 AND 30)
);

CREATE INDEX idx_products_category ON products (category_id, active);
CREATE INDEX idx_products_brand    ON products (brand_id, active);
CREATE INDEX idx_products_title    ON products (title);
CREATE INDEX idx_products_created  ON products (created_at);
