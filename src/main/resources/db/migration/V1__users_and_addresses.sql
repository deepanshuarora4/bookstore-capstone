-- V1: users, addresses (IBM steps 1, 2, 9)
-- SQL is kept portable (PostgreSQL + H2 for tests): no partial indexes, no regex CHECKs.
-- Format rules (phone, PIN code, e-mail) are enforced by request validation as specified in openapi.yaml.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,           -- BCrypt hash only, never the raw password
    phone         VARCHAR(10),
    role          VARCHAR(20)  NOT NULL DEFAULT 'CUSTOMER',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role  CHECK (role IN ('CUSTOMER', 'ADMIN'))
);

CREATE TABLE addresses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    label       VARCHAR(50),
    line1       VARCHAR(150) NOT NULL,
    line2       VARCHAR(150),
    city        VARCHAR(80)  NOT NULL,
    state       VARCHAR(80)  NOT NULL,
    postal_code VARCHAR(6)   NOT NULL,
    country     VARCHAR(60)  NOT NULL DEFAULT 'India',
    is_default  BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted     BOOLEAN      NOT NULL DEFAULT FALSE,   -- soft delete: past orders keep their snapshot
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_addresses_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_addresses_user ON addresses (user_id, deleted);
