-- V5: orders, order items, payments (IBM steps 9, 10, 11, 12, 12a)
-- Orders store price/title/address snapshots so history stays correct when the catalogue changes.
-- Card data: only card_last4 is stored. There is deliberately no column for a full card number or CVV.

CREATE TABLE orders (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number            VARCHAR(30)    NOT NULL,
    user_id                 BIGINT         NOT NULL,
    address_id              BIGINT,                          -- reference only; the snapshot below is authoritative
    status                  VARCHAR(20)    NOT NULL,
    -- delivery address snapshot
    ship_label              VARCHAR(50),
    ship_line1              VARCHAR(150)   NOT NULL,
    ship_line2              VARCHAR(150),
    ship_city               VARCHAR(80)    NOT NULL,
    ship_state              VARCHAR(80)    NOT NULL,
    ship_postal_code        VARCHAR(6)     NOT NULL,
    ship_country            VARCHAR(60)    NOT NULL,
    -- amounts in INR
    subtotal                NUMERIC(12, 2) NOT NULL,
    points_redeemed         INTEGER        NOT NULL DEFAULT 0,
    points_discount         NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total_amount            NUMERIC(12, 2) NOT NULL,
    points_earned           INTEGER        NOT NULL DEFAULT 0,
    placed_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    estimated_delivery_date DATE           NOT NULL,
    cancelled_at            TIMESTAMP WITH TIME ZONE,
    cancel_reason           VARCHAR(255),
    version                 BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_orders_order_number UNIQUE (order_number),
    CONSTRAINT fk_orders_user    FOREIGN KEY (user_id)    REFERENCES users (id),
    CONSTRAINT fk_orders_address FOREIGN KEY (address_id) REFERENCES addresses (id),
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING_PAYMENT', 'CONFIRMED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT ck_orders_subtotal        CHECK (subtotal > 0),
    CONSTRAINT ck_orders_points_redeemed CHECK (points_redeemed >= 0),
    CONSTRAINT ck_orders_points_earned   CHECK (points_earned >= 0),
    CONSTRAINT ck_orders_points_discount CHECK (points_discount >= 0),
    -- redemption is capped below 100% of the subtotal, so the payable total is always positive
    CONSTRAINT ck_orders_total_positive  CHECK (total_amount > 0),
    CONSTRAINT ck_orders_total_math      CHECK (total_amount = subtotal - points_discount),
    CONSTRAINT ck_orders_cancelled CHECK (
        (status = 'CANCELLED' AND cancelled_at IS NOT NULL) OR
        (status <> 'CANCELLED' AND cancelled_at IS NULL))
);

CREATE INDEX idx_orders_user_placed ON orders (user_id, placed_at);   -- order history, newest first
CREATE INDEX idx_orders_status      ON orders (status);

CREATE TABLE order_items (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                BIGINT         NOT NULL,
    product_id              BIGINT         NOT NULL,
    title                   VARCHAR(200)   NOT NULL,          -- snapshot
    author                  VARCHAR(150),                     -- snapshot
    unit_price              NUMERIC(10, 2) NOT NULL,          -- snapshot
    quantity                INTEGER        NOT NULL,
    line_total              NUMERIC(12, 2) NOT NULL,
    estimated_delivery_date DATE           NOT NULL,
    CONSTRAINT fk_order_items_order   FOREIGN KEY (order_id)   REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_order_items_quantity   CHECK (quantity >= 1),
    CONSTRAINT ck_order_items_price      CHECK (unit_price >= 0.01),
    CONSTRAINT ck_order_items_line_total CHECK (line_total = unit_price * quantity)
);

CREATE INDEX idx_order_items_order   ON order_items (order_id);
CREATE INDEX idx_order_items_product ON order_items (product_id);   -- Buy Again / recommendations

CREATE TABLE payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT         NOT NULL,
    method          VARCHAR(20)    NOT NULL,
    status          VARCHAR(10)    NOT NULL,
    amount          NUMERIC(12, 2) NOT NULL,
    transaction_ref VARCHAR(40),
    card_last4      VARCHAR(4)     NOT NULL,                  -- the ONLY card data ever stored
    failure_reason  VARCHAR(255),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT uq_payments_transaction_ref UNIQUE (transaction_ref),
    CONSTRAINT ck_payments_method CHECK (method IN ('CREDIT_CARD', 'DEBIT_CARD')),
    CONSTRAINT ck_payments_status CHECK (status IN ('SUCCESS', 'FAILED', 'REFUNDED')),
    CONSTRAINT ck_payments_amount CHECK (amount > 0),
    CONSTRAINT ck_payments_last4  CHECK (LENGTH(card_last4) = 4)
);

CREATE INDEX idx_payments_order ON payments (order_id, created_at);   -- latest payment of an order

-- Now that orders exists, link the gift point ledger to it.
ALTER TABLE gift_point_transactions
    ADD CONSTRAINT fk_gift_point_txn_order FOREIGN KEY (order_id) REFERENCES orders (id);
CREATE INDEX idx_gift_point_txn_order ON gift_point_transactions (order_id);
